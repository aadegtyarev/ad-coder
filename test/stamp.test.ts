test("body-check fails with the stale error when the body block differs from the ledger", () => {
  const dir = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "ad-coder-body-stale-")));
  try {
    const ledger = path.join(dir, "ledger.jsonl");
    fs.writeFileSync(ledger, `${JSON.stringify(record({ ts: 1 }))}\n`);
    const body = path.join(dir, "body.md");
    // A form-shaped stale paste: the prose lead-in plus a fenced `runs=`-headed
    // block whose totals no longer match the ledger -- the classic stale paste
    // after more ledger lines landed.
    fs.writeFileSync(
      body,
      "Delivery signature, generated by ad-coder-dev (`ad-coder-dev stamp delivery` over this run's ledger):\n\n" +
        "```\n" +
        "runs=1 | calls=99 | cost=$999.000000 | tokens fresh=0 cached=0 out=0\n" +
        "coder     vendor/small                     calls=1   cost=$0.010000\n" +
        "```\n",
    );
    const failures = stampBodyCheckErrors(body, dir, [ledger]);
    expect(failures.length).toBe(1);
    expect(failures[0]?.reason).toContain("the delivery block is stale");
    expect(failures[0]?.reason).toContain("prose lead-in with a fenced runs= block");
    expect(failures[0]?.action).toContain("ad-coder stamp delivery");
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

